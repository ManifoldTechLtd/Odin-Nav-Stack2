"""Generator for pedestrian benchmark scenes (corridor_pedestrian, office_open_pedestrian, outdoor_open_multi) and scene_meta.yaml."""
import shutil
from pathlib import Path

import yaml

BENCH = Path(__file__).resolve().parent
REAL_PLANNER = BENCH.parents[2] / "robots/sw01/neupan/planner.yaml"

ROBOT = {
    "kinematics": {"name": "diff"},
    "shape": {"name": "rectangle", "length": 0.96, "width": 0.55},
    "vel_min": [-1.0, -3.14], "vel_max": [1.0, 3.14],
    "goal_threshold": 0.25,
    "plot": {"show_trail": True, "show_goal": False, "show_trajectory": False},
    "sensors": [{"type": "lidar2d", "range_min": 0, "range_max": 8,
                 "angle_range": 2.094, "number": 200, "noise": False}],
}


def walls(rects):
    return {"number": len(rects), "distribution": {"name": "manual"},
            "shape": [{"name": "rectangle", "length": L, "width": W} for _, _, L, W in rects],
            "state": [[cx, cy, 0] for cx, cy, _, _ in rects]}


def peds(circles, rng, vmax):
    return {"number": len(circles), "distribution": {"name": "manual"},
            "shape": [{"name": "circle", "radius": r} for _, _, r in circles],
            "state": [[x, y, 0] for x, y, _ in circles],
            "kinematics": {"name": "diff"},
            "behavior": [{"name": "rvo", "range_low": [rng[0], rng[1], -3.14],
                          "range_high": [rng[2], rng[3], 3.14],
                          "wander": True, "vxmax": vmax, "vymax": vmax}],
            "vel_min": [-vmax, -3.14], "vel_max": [vmax, 3.14],
            "arrive_mode": "position", "goal_threshold": 0.3,
            "plot": {"show_goal": False, "show_arrow": True}}


SCENES = {}

# 1.3m corridor (x in [4, 12]) with wandering pedestrian
SCENES["corridor_pedestrian"] = dict(
    world={"width": 16, "height": 8, "step_time": 0.1, "sample_time": 0.1,
           "offset": [0, 0], "collision_mode": "stop", "control_mode": "auto"},
    start=[1.5, 4.0, 0.0], goal=[14.5, 4.0, 0.0],
    obs=[walls([(8.0, 6.325, 8.0, 3.35), (8.0, 1.675, 8.0, 3.35)]),
         peds([(7.5, 4.0, 0.25)], (5.5, 3.6, 10.5, 4.4), 0.4)],
)

# Semi-open office with desks/partitions and 2 pedestrians
SCENES["office_open_pedestrian"] = dict(
    world={"width": 20, "height": 14, "step_time": 0.1, "sample_time": 0.1,
           "offset": [0, -7], "collision_mode": "stop", "control_mode": "auto"},
    start=[1.0, 0.0, 0.0], goal=[19.0, 0.0, 0.0],
    obs=[walls([(5.0, 3.0, 1.4, 0.7), (5.0, -3.0, 1.4, 0.7), (10.0, 1.8, 0.7, 1.4),
                (10.0, -1.8, 0.7, 1.4), (15.0, 3.0, 1.4, 0.7), (15.0, -3.0, 1.4, 0.7)]),
         peds([(7.0, 1.0, 0.25), (13.0, -1.0, 0.25)], (3.0, -2.5, 17.0, 2.5), 0.6)],
)

# Open outdoor 40x24m area with 4 pedestrians
SCENES["outdoor_open_multi"] = dict(
    world={"width": 40, "height": 24, "step_time": 0.1, "sample_time": 0.1,
           "offset": [0, -12], "collision_mode": "stop", "control_mode": "auto"},
    start=[2.0, 0.0, 0.0], goal=[38.0, 0.0, 0.0],
    obs=[peds([(10.0, 2.0, 0.25), (18.0, -2.0, 0.25), (26.0, 1.5, 0.25), (32.0, -1.5, 0.25)],
              (5.0, -3.0, 35.0, 3.0), 0.9)],
)


def main():
    for name, sc in SCENES.items():
        d = BENCH / name
        d.mkdir(exist_ok=True)
        robot = dict(ROBOT)
        robot["state"] = list(sc["start"])
        robot["goal"] = list(sc["goal"])
        env = {"world": sc["world"], "robot": [robot], "obstacle": sc["obs"]}
        with open(d / "env.yaml", "w") as f:
            f.write(f"# Pedestrian scene {name} (generated by gen_ped_scenes.py)\n")
            yaml.safe_dump(env, f, allow_unicode=True, sort_keys=False)
        shutil.copy(REAL_PLANNER, d / "planner.yaml")
        print(f"Generated {name}")

    meta = {}
    for d in sorted(BENCH.glob("*/env.yaml")):
        name = d.parent.name
        try:
            c = yaml.safe_load(open(d))
        except Exception:
            continue
        obs = c.get("obstacle", []) or []
        n_ped = sum(int(o.get("number", 1)) for o in obs if o.get("behavior"))
        n_unk = sum(int(o.get("number", 1)) for o in obs if o.get("exclude_from_static"))
        w = c.get("world", {})
        gaps = []
        ys = []
        for o in obs:
            if o.get("behavior") or o.get("exclude_from_static"):
                continue
            for sh, st in zip(o.get("shape", []), o.get("state", [])):
                if sh.get("name") == "rectangle":
                    ys.append((st[1], sh.get("width", 0)))
        for i in range(len(ys)):
            for j in range(i + 1, len(ys)):
                g = abs(ys[i][0] - ys[j][0]) - (ys[i][1] + ys[j][1]) / 2
                if 0.4 < g < 3.0:
                    gaps.append(g)
        kind = ("open" if not gaps and n_ped else
                "corridor" if gaps and min(gaps) < 1.6 else "office")
        meta[name] = {"type": kind, "pedestrians": n_ped, "unknown_obs": n_unk,
                      "min_gap_m": round(min(gaps), 2) if gaps else None,
                      "world": f"{w.get('width')}x{w.get('height')}"}
    meta["corridor_pedestrian"]["purpose"] = "Narrow corridor pedestrian avoidance"
    meta["office_open_pedestrian"]["purpose"] = "Semi-open office pedestrian avoidance"
    meta["outdoor_open_multi"]["purpose"] = "Open outdoor multi-pedestrian avoidance"
    meta["dynamic_human"]["purpose"] = "Open 3-pedestrian crossing"
    meta["ghost_corner"]["purpose"] = "Corner occlusion unknown obstacle and memory decay"
    with open(BENCH / "scene_meta.yaml", "w") as f:
        yaml.safe_dump(meta, f, allow_unicode=True, sort_keys=True)
    print(f"scene_meta.yaml: {len(meta)} scenes registered")


if __name__ == "__main__":
    main()
