"""Generator for prescreen scenes: corner90, corridor110, corridor130, narrow09_entry, deadend_T."""
import shutil
from pathlib import Path

import yaml

BENCH = Path(__file__).resolve().parent
REAL_PLANNER = BENCH.parents[2] / "robots/sw01/neupan/planner.yaml"

ROBOT = {
    "kinematics": {"name": "diff"},
    "shape": {"name": "rectangle", "length": 0.96, "width": 0.55},
    "vel_min": [-1.0, -3.14], "vel_max": [1.0, 3.14],
    "goal_threshold": 0.25,
    "plot": {"show_trail": True, "show_goal": False, "show_trajectory": False},
    "sensors": [{"type": "lidar2d", "range_min": 0, "range_max": 8,
                 "angle_range": 2.094, "number": 200, "noise": False}],
}


def rect(cx, cy, L, W):
    return {"shape": [{"name": "rectangle", "length": L, "width": W}],
            "state": [[cx, cy, 0]]}


def merge_rects(rects):
    """Merge rectangle obstacle definitions into a single irsim obstacle entry."""
    shapes, states = [], []
    for r in rects:
        shapes.extend(r["shape"])
        states.extend(r["state"])
    return {"number": len(shapes), "distribution": {"name": "manual"},
            "shape": shapes, "state": states}


SCENES = {}

# corner90: L-shaped 1.2m corridor with 90-degree turn
SCENES["corner90"] = dict(
    world={"width": 14, "height": 14, "step_time": 0.1, "sample_time": 0.1,
           "offset": [-1, -1], "collision_mode": "stop", "control_mode": "auto"},
    start=[0.0, 0.6, 0.0], goal=[6.6, 10.4, 0.0],
    walls=[rect(3.5, -0.525, 9.0, 0.95),      # S
           rect(2.475, 7.125, 6.95, 11.75),   # NW
           rect(10.125, 6.0, 5.75, 14.0),     # E
           rect(6.6, 12.075, 1.3, 1.85)],     # N cap
)

# corridor110 / corridor130 / narrow09_entry: straight corridor with open ends
def straight_corridor(half_w):
    y_lo, y_hi = 4.0 - half_w, 4.0 + half_w
    return dict(
        world={"width": 16, "height": 8, "step_time": 0.1, "sample_time": 0.1,
               "offset": [0, 0], "collision_mode": "stop", "control_mode": "auto"},
        start=[1.5, 4.0, 0.0], goal=[14.5, 4.0, 0.0],
        walls=[rect(8.0, (y_hi + 8) / 2, 8.0, 8 - y_hi),
               rect(8.0, y_lo / 2, 8.0, y_lo)],
    )

SCENES["corridor110"] = straight_corridor(0.55)
SCENES["corridor130"] = straight_corridor(0.65)
SCENES["narrow09_entry"] = straight_corridor(0.45)

# deadend_T: horizontal corridor with a 1.2m dead-end stub
SCENES["deadend_T"] = dict(
    world={"width": 14, "height": 8, "step_time": 0.1, "sample_time": 0.1,
           "offset": [0, 0], "collision_mode": "stop", "control_mode": "auto"},
    start=[12.0, 1.2, 3.14159], goal=[7.0, 4.55, 1.5708],
    walls=[rect(3.2, 4.925, 6.4, 6.15),       # N-left
           rect(10.8, 4.925, 6.4, 6.15),      # N-right
           rect(7.0, 0.275, 14.0, 0.55),      # S
           rect(5.975, 3.425, 0.75, 3.25),    # stub W
           rect(8.025, 3.425, 0.75, 3.25),    # stub E
           rect(7.0, 5.425, 1.3, 0.75)],      # dead-end cap
)


def main():
    for name, sc in SCENES.items():
        d = BENCH / name
        d.mkdir(exist_ok=True)
        robot = dict(ROBOT)
        robot["state"] = list(sc["start"])
        robot["goal"] = list(sc["goal"])
        env = {"world": sc["world"], "robot": [robot],
               "obstacle": [merge_rects(sc["walls"])]}
        with open(d / "env.yaml", "w") as f:
            f.write(f"# Prescreen scene {name} (generated by gen_prescreen_scenes.py)\n")
            yaml.safe_dump(env, f, allow_unicode=True, sort_keys=False)
        shutil.copy(REAL_PLANNER, d / "planner.yaml")
        print(f"Generated {name}: env.yaml + planner.yaml")


if __name__ == "__main__":
    main()
