"""Batch generator for SW01 benchmark scene planner.yaml configurations."""
from pathlib import Path
import yaml

BENCH = Path(__file__).resolve().parent

BASE = {
    "receding": 10, "step_time": 0.1, "ref_speed": 0.5,
    "device": "cpu", "time_print": False, "collision_threshold": 0.05,
    "robot": {"kinematics": "diff", "max_speed": [1.0, 1.0], "max_acce": [0.5, 0.5],
              "length": 0.96, "width": 0.55},
    "ipath": {"waypoints": [], "curve_style": "line", "min_radius": 0.2,
              "loop": False, "arrive_threshold": 0.25, "close_threshold": 0.1,
              "ind_range": 30, "arrive_index_threshold": 1},
    "pan": {"iter_num": 2, "dune_max_num": 100, "nrmp_max_num": 10,
            "dune_checkpoint": "example/dune_train/model/sw01/model_5000.pth",
            "iter_threshold": 0.1},
    "adjust": {"q_s": 1.0, "q_theta": 1.0, "p_u": 1.0, "p_w": 0.8,
               "eta": 12.0, "ro_obs": 400, "d_max": 0.4, "d_min": 0.05, "bk": 0.4},
}

SCENES = {
    "narrow_to_wide": {"waypoints": [[13, 0, 0]]},
    "wide_to_narrow": {"waypoints": [[13, 0, 0]]},
    "head_on":        {"waypoints": [[22, 0, 0]]},
    "human_block":    {"waypoints": [[16, 0, 0]], "ref_speed": 0.4,
                       "adjust": {"eta": 15.0, "ro_obs": 500, "d_max": 0.5}},
    "office":         {"waypoints": [[2, -0.5, 0], [3.5, -0.8, 0], [5, -0.8, 0], [6.5, -0.65, 0],
                                     [8, -0.3, 0], [9.5, 0, 0], [11, 0, 0], [12.5, 0, 0],
                                     [14, 0, 0], [14.5, 0, 0]],
                       "adjust": {"d_max": 0.15, "eta": 10.0}},
}

for scene, diff in SCENES.items():
    cfg = yaml.safe_load(yaml.safe_dump(BASE))  # deep copy
    cfg["ipath"]["waypoints"] = diff["waypoints"]
    if "ref_speed" in diff:
        cfg["ref_speed"] = diff["ref_speed"]
    if "adjust" in diff:
        cfg["adjust"].update(diff["adjust"])
    out = BENCH / scene / "planner.yaml"
    with open(out, "w") as f:
        f.write(f"# SW01 benchmark - {scene} (generated by gen_planners.py)\n")
        yaml.safe_dump(cfg, f, allow_unicode=True, default_flow_style=False, sort_keys=False)
    print(f"Generated {out}")

print("Done")
